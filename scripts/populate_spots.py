# Check if spots table already has data with auto-increment
# Let's first count
cur.execute("SELECT COUNT(*) FROM spots")
count = cur.fetchone()[0]
print(f"Existing spots: {count}")

# Check if the id is auto-increment and what the next value should be
cur.execute("SELECT MAX(id) FROM spots")
max_id = cur.fetchone()[0]
next_id = (max_id or 0) + 1
print(f"Next ID: {next_id}")

# Also check spot_review table
cur.execute("SELECT COUNT(*) FROM spot_reviews")
review_count = cur.fetchone()[0]
print(f"Existing reviews: {review_count}")

# Insert spots
inserted = 0
for spot in spots:
    name, category, desc, address, lat, lng = spot
    popularity = random.randint(50, 5000)
    avg_rating = round(random.uniform(3.0, 5.0), 1)
    try:
        cur.execute("""
            INSERT INTO spots (id, name, category, description, address, latitude, longitude, 
                              popularity, avg_rating, rating_count, created_at)
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, NOW())
        """, (next_id, name, category, desc, address, lat, lng, popularity, avg_rating, random.randint(1, 100)))
        next_id += 1
        inserted += 1
    except Exception as e:
        print(f"  Error inserting {name}: {e}")

conn.commit()
print(f"\nInserted {inserted} new spots")
print(f"Total: {count + inserted}")

# Verify categories
cur.execute("SELECT category, COUNT(*) FROM spots GROUP BY category ORDER BY COUNT(*) DESC")
cats = cur.fetchall()
print("\nCategories:")
for c, cnt in cats:
    print(f"  {c}: {cnt}")

